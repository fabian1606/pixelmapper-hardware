#!/usr/bin/env python3
"""protocol/vectors/**/*.json -> C source with all vectors (stdlib only).

usage: vectors_to_c.py <vectors_dir> <out.c>
Nested objects are flattened with '.', arrays with '[i]'. Booleans become numbers 0/1.
"""
import json
import pathlib
import sys


def flatten(prefix, v, out):
    if isinstance(v, dict):
        for k, x in v.items():
            flatten(f"{prefix}.{k}" if prefix else k, x, out)
    elif isinstance(v, list):
        for i, x in enumerate(v):
            flatten(f"{prefix}[{i}]", x, out)
    elif isinstance(v, bool):
        out.append((prefix, 1, int(v), None))
    elif isinstance(v, int):
        out.append((prefix, 1, v, None))
    elif v is None:
        out.append((prefix, 0, 0, ""))
    else:
        out.append((prefix, 0, 0, str(v)))


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    root, out_path = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    lines = ['/* @generated by test_host/tools/vectors_to_c.py - do not edit */', '#include "vectors.h"', ""]
    entries = []
    for f in sorted(root.rglob("*.json")):
        if f.name == "schema.json":
            continue
        d = json.loads(f.read_text())
        for v in d["vectors"]:
            i = len(entries)
            data = bytes.fromhex("".join(v["hex"].split()))
            body = ", ".join(f"0x{b:02x}" for b in data) or "0"
            lines.append(f"static const uint8_t v{i}_bytes[] = {{{body}}};")
            fl = []
            flatten("", v["fields"], fl)
            fs = ", ".join(f"{{{cstr(k)}, {isnum}, {num}LL, {cstr(s) if s is not None else 'NULL'}}}"
                           for k, isnum, num, s in fl) or '{NULL, 0, 0, NULL}'
            lines.append(f"static const pm_vec_field_t v{i}_fields[] = {{{fs}}};")
            entries.append(f"    {{{cstr(d['protocol'])}, {cstr(d['packet'])}, {cstr(v['name'])}, "
                           f"{int(v['valid'])}, v{i}_bytes, {len(data)}u, v{i}_fields, {len(fl)}u}},")
    lines.append("")
    lines.append("const pm_vec_t pm_vectors[] = {")
    lines += entries
    lines.append("};")
    lines.append(f"const size_t pm_vectors_count = {len(entries)}u;")
    out_path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
